#!/usr/bin/env node
/**
 * Generates frontend/src/i18n/serverErrorMap.ts and the English `serverErrors`
 * locale skeleton from backend AppError literals + format! templates.
 *
 *   node scripts/gen-server-error-map.mjs
 *
 * Writes:
 *   frontend/src/i18n/serverErrorMap.ts   (literal map + regex patterns)
 *   /tmp/serverErrors.en.ts               (paste into locales/en.ts)
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const BE_SRC = join(ROOT, 'backend', 'src');

function* walk(dir) {
  for (const e of readdirSync(dir)) {
    const f = join(dir, e);
    const st = statSync(f);
    if (st.isDirectory()) yield* walk(f);
    else if (f.endsWith('.rs') && !f.includes('/tests/')) yield f;
  }
}

// Rust escapes inside a string literal: backslash-newline continuation,
// \n, \" and \\.
const normalize = (s) =>
  s
    .replace(/\\\n\s*/g, ' ')
    .replace(/\\n/g, ' ')
    .replace(/\\"/g, '"')
    .replace(/\\\\/g, '\\')
    .replace(/\s+/g, ' ')
    .trim();

const literals = new Set();
const templates = []; // {tpl, file}
for (const file of walk(BE_SRC)) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(/AppError::\w+\(\s*"((?:[^"\\]|\\[\s\S])*)"/g)) {
    literals.add(normalize(m[1]));
  }
  for (const m of src.matchAll(/AppError::\w+\(\s*format!\(\s*"((?:[^"\\]|\\[\s\S])*)"/g)) {
    templates.push(normalize(m[1]));
  }
}

// Slugify a message into a camelCase key fragment.
function slug(text) {
  const words = text
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
    .slice(0, 8);
  return words.map((w, i) => (i === 0 ? w : w[0].toUpperCase() + w.slice(1))).join('');
}

// Turn a format! template into {re-source, args, enText}
function templateToPattern(tpl) {
  const args = [];
  let i = 0;
  // {name}, {}, {:02}, {MAX_X} consts → capture groups; {ident} gets its name.
  const parts = tpl.split(/(\{[^}]*\})/g).map((part) => {
    const m = part.match(/^\{(?:(\w+))?(?::[^}]*)?\}$/);
    if (!m) return part.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
    const name = m[1] && /^[a-z]/i.test(m[1]) && !/^[A-Z_]+$/.test(m[1]) ? m[1] : `arg${i}`;
    i++;
    args.push(name);
    return '(.+)';
  });
  // en text: replace captures with {{name}} for i18next
  let j = 0;
  const enText = tpl.replace(/\{(?:(\w+))?(?::[^}]*)?\}/g, (_, nm) => {
    const name = nm && /^[a-z]/i.test(nm) && !/^[A-Z_]+$/.test(nm) ? nm : `arg${j}`;
    j++;
    return `{{${name}}}`;
  });
  return { re: `^${parts.join('')}$`, args, enText };
}

const seen = new Map(); // slug -> key assignment
function keyFor(text) {
  let base = slug(text) || 'message';
  let k = base;
  let n = 2;
  while (seen.has(k) && seen.get(k) !== text) k = `${base}${n++}`;
  seen.set(k, text);
  return `serverErrors.${k}`;
}

const literalEntries = [...literals].sort().map((msg) => [msg, keyFor(msg)]);
const patterns = [];
const enEntries = new Map(literalEntries.map(([msg, k]) => [k.slice('serverErrors.'.length), msg]));

const usedPatterns = new Set();
for (const tpl of [...new Set(templates)].sort()) {
  const { re, args, enText } = templateToPattern(tpl);
  if (usedPatterns.has(re)) continue;
  usedPatterns.add(re);
  const key = keyFor(enText.replace(/\{\{\w+\}\}/g, 'x'));
  patterns.push({ re, key, args });
  if (!enEntries.has(key.slice('serverErrors.'.length))) {
    enEntries.set(key.slice('serverErrors.'.length), enText);
  }
}

const esc = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

let out = `/**
 * GENERATED by scripts/gen-server-error-map.mjs — regenerate after backend
 * AppError messages change. Exact literals → keys; format! templates →
 * patterns with named captures for interpolation.
 */
export interface ServerErrorPattern {
  re: RegExp;
  key: string;
  args: string[];
}

export const SERVER_ERROR_KEYS: Record<string, string> = {
`;
for (const [msg, key] of literalEntries) out += `  ${esc(msg)}: '${key}',\n`;
out += `};\n\nexport const SERVER_ERROR_PATTERNS: ServerErrorPattern[] = [\n`;
for (const p of patterns) {
  out += `  { re: /${p.re}/, key: '${p.key}', args: ${JSON.stringify(p.args)} },\n`;
}
out += `];\n`;

writeFileSync(join(ROOT, 'frontend/src/i18n/serverErrorMap.ts'), out);

let en = '  serverErrors: {\n';
for (const [k, v] of [...enEntries.entries()].sort()) {
  en += `    ${JSON.stringify(k)}: ${esc(v)},\n`;
}
en += '  },\n';
writeFileSync('/tmp/serverErrors.en.ts', en);
console.log(`literals: ${literalEntries.length}, patterns: ${patterns.length}, en entries: ${enEntries.size}`);
console.log('wrote frontend/src/i18n/serverErrorMap.ts and /tmp/serverErrors.en.ts');
